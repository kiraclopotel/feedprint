/**
 * One time-stamp token, opened offline: the certificates travel inside it.
 * Three readings, as on the export's own page: verified under an authority
 * this checker recognises; verified under one it does not (anyone can run a
 * timestamping service and sign their own tokens, so that reading names the
 * certificate instead of calling the token good); failed.
 */
async function openToken(anchor, expectedHashHex) {
  const api = __FW_RFC3161__;
  let v;
  try {
    v = await api.verifyAnchorBase64({ tst: anchor.tstB64, response: anchor.responseB64 }, expectedHashHex);
  } catch (err) {
    return { ok: false, authority: null, signer: null, genTime: null, rootCertSha256: null, failed: [], error: String(err && err.message || err) };
  }
  return {
    ok: !!v.ok,
    authority: v.knownRootName || null,
    signer: api.shortSubject(v.signerSubject),
    genTime: v.genTime,
    rootCertSha256: v.rootCertSha256,
    failed: (v.checks || []).filter((c) => !c.ok).map((c) => c.name),
    error: v.error || null,
  };
}

/**
 * The chain anchors, each against the record hash it names, and the stamp
 * over the signing key against a digest RECOMPUTED from the key in the file,
 * never the digest the file states beside it. A verified token under an
 * unrecognised authority never dates the key.
 */
async function checkTimestamps(data, sha256) {
  const out = { anchors: [], keyGenesis: null };
  const anchors = (data.anchors || []).slice().sort((a, b) => a.anchoredChainPosition - b.anchoredChainPosition);
  for (const a of anchors) {
    const t = await openToken(a, a.anchoredIntegrityHash);
    out.anchors.push({ position: a.anchoredChainPosition, recordHash: a.anchoredIntegrityHash, provider: a.tsaProvider || null, ...t });
  }
  const kg = data.keyGenesis;
  if (kg && Array.isArray(kg.anchors) && kg.anchors.length) {
    const jwk = data.publicKeyJwk || {};
    const expected = await sha256((jwk.x || '') + '|' + (jwk.y || ''));
    const stamps = [];
    for (const a of kg.anchors) stamps.push({ provider: a.tsaProvider || null, ...(await openToken(a, expected)) });
    let existedBy = null; const who = [];
    for (const s of stamps) {
      if (!s.ok || !s.genTime || !s.authority) continue;
      if (who.indexOf(s.authority) < 0) who.push(s.authority);
      if (!existedBy || s.genTime < existedBy) existedBy = s.genTime;
    }
    out.keyGenesis = { expectedDigest: expected, statedDigest: kg.publicKeyDigest || null, existedBy, authorities: who, stamps };
  }
  return out;
}

/**
 * The same walk the embedded verifier makes (runVerification in
 * html-export.ts), without a page to paint: keys, every record, withheld
 * records on their markers, the chain, the anchors, the manifest.
 */
async function verifyExportText(text) {
  const { data, html } = parseExport(text);
  const v = createVerifier(provenanceDocument(html));
  const report = { state: 'failed', manifest: 'missing', records: 0, keys: 0, failures: [], unverified: { priorKey: 0, unsigned: 0, signatureUnverified: 0, signatureRejected: 0 }, carriedKey: 0, redacted: 0, holding: null, chain: null, anchors: null, coverage: null, notes: [], noteParts: [] };
  // 'holding' is initialised here and not only assigned on the way out, because
  // FORMAT.md section 8 tells a checker that a terminal failure reports
  // holding: null, and the two early returns below returned a report with no
  // holding key at all. vectors/EXPECTED.json said null on both of them, since
  // the vector generator's projection normalises an absent field to null, so the
  // published comparison target disagreed with the checker that produced it and
  // an implementer diffing a raw report against it saw a difference the spec had
  // told them not to expect (found 2026-09-18 by a claim check of FORMAT.md
  // against this file).

  let redactedOnPriorKey = 0;
  // Two more reasons a withheld record's signature was not checked, both of
  // which the note below counted as checked until 2026-09-19. The first is
  // live: a withheld record with no signature field at all is accepted on its
  // marker, which is right, but the reader was told its signature had been
  // verified. The second cannot be reached through this entry point today,
  // because a file whose own key fails to set up returns at key-setup above;
  // it is counted anyway, since counting only the reachable cases is what
  // produced the first one.
  let redactedUnsigned = 0;
  let redactedNoKey = 0;
  let keySetup;
  try {
    keySetup = await v.importVerifiedPubKey(data.publicKeyJwk, data.publicKeyFingerprint);
  } catch (err) {
    report.failures.push({ index: -1, id: null, reason: 'key-setup', detail: String(err && err.message || err) });
    return report;
  }
  report.manifest = await v.checkManifest(data, keySetup.pubKey, keySetup.fingerprint);
  // WHICH of the page's statements the signature covered, not merely that it
  // matched. An older file marks fewer rows, so this is a fact about the file in
  // the reader's hands rather than about the checker, and landing/check.html
  // promised a reader they could read it here before anything produced it
  // (found 2026-09-18 by checking that page's claims against the code).
  report.coveredRows = v.provenanceRowNames();
  // 'no-rows' joins 'missing' and 'legacy' as a manifest that was not fully
  // checked rather than one that failed: a bare JSON envelope carries no page
  // rows to compare, which is a property of the input form, not evidence
  // against the file. Everything else in the manifest was still verified.
  if (report.manifest !== 'ok' && report.manifest !== 'missing' && report.manifest !== 'legacy' && report.manifest !== 'no-rows') {
    report.failures.push({ index: -1, id: null, reason: 'manifest', detail: report.manifest });
    return report;
  }
  const keys = {};
  keys[keySetup.fingerprint] = keySetup.pubKey;
  for (const carried of data.publicKeys || []) {
    try {
      const k = await v.importVerifiedPubKey(carried.jwk, carried.fingerprint);
      keys[k.fingerprint] = k.pubKey;
    } catch (_skip) { /* a carried key that fails its own fingerprint is left out; its records verify by hash only */ }
  }
  report.keys = Object.keys(keys).length;
  const records = Array.isArray(data.records) ? data.records : [];
  report.records = records.length;
  const redactions = v.redactionIndex(records);
  const perRecord = [];
  for (let i = 0; i < records.length; i++) perRecord.push(await v.verifyOne(records[i], keys, keySetup.fingerprint, redactions));
  const markerOk = {};
  for (let i = 0; i < records.length; i++) if (records[i] && records[i].kind === 'redaction-marker') markerOk[records[i].id] = !!(perRecord[i] && perRecord[i].ok);
  for (let i = 0; i < perRecord.length; i++) { const p = perRecord[i]; if (p && p.redacted && markerOk[p.markerId] === false) perRecord[i] = { ok: false, reason: 'redaction-unattested' }; }
  for (let i = 0; i < perRecord.length; i++) {
    const p = perRecord[i];
    if (!p.ok) {
      report.failures.push({
        index: i, id: records[i] && records[i].id || null, reason: p.reason,
        ...(p.unknownFields && p.unknownFields.length ? { unknownFields: p.unknownFields } : {}),
      });
      continue;
    }
    if (p.redacted) report.redacted++;
    // Withheld AND on a key this file does not carry: accepted by its marker
    // alone, with no signature check, because there is no key here to check it
    // under. Kept apart from report.redacted so the note below can say which of
    // the two a reader is holding.
    if (p.redacted && p.priorKey) redactedOnPriorKey++;
    if (p.redacted && p.noSignature) redactedUnsigned++;
    if (p.redacted && p.noKey) redactedNoKey++;
    if (p.carriedKey) report.carriedKey++;
    if (p.unverified) {
      if (p.unsigned) report.unverified.unsigned++;
      else if (p.priorKey) report.unverified.priorKey++;
      else if (p.signatureRejected) report.unverified.signatureRejected++;
      else report.unverified.signatureUnverified++;
    }
  }
  report.chain = await v.verifyChain(records, perRecord);
  report.anchors = v.anchorFindings(records, data.anchors || []);
  report.coverage = v.coverageFromRecords(records);
  // What the file says it is (selectionOf in the core): a report states how
  // many records it holds of how many the install had; the whole record
  // states nothing and holds everything the install still had.
  const sel = v.selectionOf(data, records);
  // Archived records the install says under its signature it could not read (unreadableOf in the
  // core). They are why a whole record can be less than everything the install held.
  const unreadable = v.unreadableOf(data, report.manifest);
  const keyStamped = !!(data.keyGenesis && Array.isArray(data.keyGenesis.anchors) && data.keyGenesis.anchors.length);
  report.holding = {
    kind: sel ? 'report' : (html ? 'whole-record' : 'envelope'),
    records: records.length,
    included: sel ? sel.included : records.length,
    totalSource: sel ? sel.totalSource : null,
    leftOut: sel ? sel.leftOut : 0,
    generatedAt: data.manifest && typeof data.manifest.generatedAt === 'string' ? data.manifest.generatedAt : null,
    fwVersion: typeof data.fwVersion === 'string' ? data.fwVersion : null,
    fingerprint: keySetup.fingerprint,
    anchors: (data.anchors || []).length,
    keyStamped,
    // Is the "whole record" claim backed by anything this checker verified?
    // The kind above is decided by the ABSENCE of a selection field, which the
    // file itself supplies, so on its own it is the file's word. The signed
    // manifest is what turns it into a checked statement: its recordsDigest
    // covers the record set and its envelopeDigest covers the selection field.
    //
    // 'no-rows' counts here. checkManifest verifies recordsDigest and
    // envelopeDigest BEFORE it reaches the page rows, so a bare JSON envelope
    // whose only unchecked part is the rendered rows still has its record set
    // and its selection field verified — removing or reordering a record in one
    // breaks recordsDigest exactly as it does in the HTML.
    manifestOk: false,
    unreadable,
  };
  report.holding.manifestOk = report.manifest === 'ok' || report.manifest === 'no-rows';
  let state = v.verificationState(perRecord, report.chain, { anchors: report.anchors, coverage: report.coverage, selection: sel });
  if ((report.manifest === 'missing' || report.manifest === 'legacy' || report.manifest === 'no-rows') && state === 'verified') state = 'partial';
  report.state = state;
  // A missing manifest names the innocent reason only when the file's own dates allow it (the tester's finding 1,
  // 8 Oct 2026: a file of 28 September records with its manifest deleted read "made by a build before 2026-09-06").
  // Those dates are in the file, so whoever took the manifest out can backdate one record or drop the dates: then the
  // note names both cases, an older build or a removed manifest (the head, 9 Oct 2026). A version-1 manifest is an
  // older build's own and keeps its note.
  const firstDay = oldestRecordDay(records);
  const datedAfterManifests = report.manifest === 'missing' && firstDay !== null && firstDay >= MANIFEST_SINCE;
  pushNote(report, 'noteNoManifestDated', { first: firstDay || '' }, datedAfterManifests);
  pushNote(report, 'noteNoManifestEither', {}, report.manifest === 'missing' && !datedAfterManifests);
  pushNote(report, 'noteNoManifest', {}, report.manifest === 'legacy');
  pushNote(report, 'noteBareEnvelope', {}, report.manifest === 'no-rows');
  // Named, not counted. A reader comparing two files, or reading one made before
  // a widening, is being told which of the page's statements the signature
  // stands behind. The count alone would answer a question nobody asked.
  pushNote(report, 'noteCoveredRows', { n: (report.coveredRows || []).length, rows: (report.coveredRows || []).join(', ') },
    report.manifest === 'ok' && (report.coveredRows || []).length > 0);
  for (const line of report.chain.setAsideLines || []) {
    pushNote(report, 'noteSetAside', { n: line.n, position: line.position >= 0 ? line.position : '?' }, true);
  }
  const seams = (report.chain.branches || 0) + (report.chain.restarts || 0);
  pushNote(report, 'noteSeams', { n: seams }, seams > 0);
  pushNote(report, 'noteUnattributed', { n: report.chain.unattributed }, report.chain.unattributed > 0);
  if (report.chain.outside > 0) {
    const leftOutOnPurpose = !!sel && report.chain.outside <= sel.leftOut;
    const notRead = !leftOutOnPurpose && unreadable > 0 && report.chain.outside <= unreadable;
    pushNote(report, 'noteOutsideSelection',
      { n: report.chain.outside, included: sel ? sel.included : 0, total: sel ? sel.totalSource : 0 }, leftOutOnPurpose);
    pushNote(report, 'noteOutsideUnreadable', { n: report.chain.outside, u: unreadable }, notRead);
    pushNote(report, 'noteOutside', { n: report.chain.outside }, !leftOutOnPurpose && !notRead);
  }
  // Content withheld. The reader is told plainly, because the headline verdict
  // says "every hash recomputed" and for these records it was not: their
  // content has left the file, so the hash cannot be recomputed and the record
  // stands on a signed redaction marker plus its own signature over that hash.
  // Counted since the marker shipped and printed nowhere until 2026-09-08.
  //
  // The sentence used to end "and its signature over that hash was checked",
  // of all of them. For a withheld record on a rotated key there is no key in
  // this file to check it under, so it was not checked and the reader was
  // being told it was (2026-09-18). The same sentence was still reaching a
  // reader over a record with no signature at all, which is accepted on its
  // marker and was being counted among the checked (2026-09-19); the two are
  // one defect met twice, a count that named one reason out of three.
  //
  // The three counts are carried as counts rather than as an assembled clause,
  // because "carries" against "carry" is an English agreement rule and every
  // language needs its own. redactionSentence() below builds it per language.
  if (report.redacted > 0) {
    const unchecked = redactedOnPriorKey + redactedUnsigned + redactedNoKey;
    pushNote(report, 'noteRedacted', {
      n: report.redacted,
      checked: report.redacted - unchecked,
      unsigned: redactedUnsigned,
      priorKey: redactedOnPriorKey,
      noKey: redactedNoKey,
    }, true);
  }
  pushNote(report, 'noteNoTimeStamp', {}, report.holding.anchors === 0 && !keyStamped);
  pushNote(report, 'noteStampedNotInFile', { n: report.anchors.notInFile }, report.anchors.notInFile > 0);
  pushNote(report, 'noteStampBeyond', { position: report.anchors.beyondPosition }, report.anchors.beyondTail > 0);
  report.timestamps = await checkTimestamps(data, v.sha256);
  // Per run, how many records a stamp stands behind, counted as page one counts them but only over
  // tokens this checker opened and verified under a pinned authority, with the time signed inside
  // each. The file's own word that a token checked is what is being tested, so it counts for nothing.
  const checked = report.timestamps.anchors
    .filter((a) => a.ok && a.authority)
    .map((a) => ({ anchoredChainPosition: a.position, anchoredIntegrityHash: a.recordHash, generalizedTime: a.genTime || null }));
  report.stampCoverage = v.stampCoverage(records, checked);
  return report;
}

