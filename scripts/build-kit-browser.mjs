// Writes verifier/kit.browser.js: the pool and table tools beside the checker, as one plain script a page opened
// from a local file can load. Chrome refuses ES modules from file://, and a group that double-clicks panel.html has
// no server, so the modules are wrapped here instead of copied by hand: each keeps its own scope (corroborate.mjs
// and observations.mjs both define parseExport and contentIdentity), its imports read the scope of the module they
// name, and everything from `export async function main(` on is dropped, because that part reads and writes files.
//
//   node scripts/build-kit-browser.mjs           writes the file
//   node scripts/build-kit-browser.mjs --check   exits 1 when the file on disk is not what this would write

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const VERIFIER = join(here, '..', 'verifier');
export const KIT_BROWSER_PATH = join(VERIFIER, 'kit.browser.js');

// In dependency order: a module may import only from those above it, or from the checker, which the page loads
// first as verify-export.browser.js and which this file reads through window.FWVerifier.
const MODULES = ['corroborate', 'observations', 'pool', 'to-csv', 'to-4cat'];

const HEAD = `// kit.browser.js: the pool and table tools of this folder, for panel.html, in a browser.
//
// Copyright 2026 FeelingWise. Licensed under the Apache License, Version 2.0;
// see the LICENSE file beside this one.
//
// GENERATED by scripts/build-kit-browser.mjs from ${MODULES.map((m) => m + '.mjs').join(', ')}
// beside this file. Edit those, then run: node scripts/build-kit-browser.mjs
// Needs verify-export.browser.js loaded first. Exposes one global, window.FWKit. Runs offline and contacts nothing.

(function () {
'use strict';
var webcrypto = undefined;
var M_verify_export = window.FWVerifier;
`;

const TAIL = `
window.FWKit = { pool: M_pool, toCsv: M_to_csv, to4cat: M_to_4cat };
})();
`;

function scopeName(file) {
  return 'M_' + file.replace(/^\.\//, '').replace(/\.mjs$/, '').replace(/-/g, '_');
}

/** One module's text as a function scope that returns its exports. */
export function wrapModule(name, source) {
  const cut = source.indexOf('export async function main(');
  const body = (cut === -1 ? source : source.slice(0, cut)).replace(/^#!.*\n/, '');
  const exported = [];
  const lines = [];
  for (const line of body.split('\n')) {
    const imp = /^import \{([^}]+)\} from '([^']+)';$/.exec(line);
    if (imp) {
      // Node's own modules have no browser counterpart; the parts that need them were cut with main().
      if (imp[2].startsWith('node:')) continue;
      const names = imp[1].split(',').map((n) => n.trim()).filter(Boolean).map((n) => n.replace(/\s+as\s+/, ': '));
      lines.push(`const { ${names.join(', ')} } = ${scopeName(imp[2])};`);
      continue;
    }
    if (/^import /.test(line)) throw new Error(`${name}.mjs: an import this build cannot read: ${line}`);
    const exp = /^export (async function|function|const|let) ([A-Za-z_$][\w$]*)/.exec(line);
    if (exp) {
      exported.push(exp[2]);
      lines.push(line.replace(/^export /, ''));
      continue;
    }
    if (/^export /.test(line)) throw new Error(`${name}.mjs: an export this build cannot read: ${line}`);
    lines.push(line);
  }
  return `\n// ── ${name}.mjs ${'─'.repeat(Math.max(3, 70 - name.length))}\nvar ${scopeName(name + '.mjs')} = (function () {\n`
    + lines.join('\n').trimEnd()
    + `\nreturn { ${exported.join(', ')} };\n})();\n`;
}

export function buildKitBrowserSource() {
  return HEAD + MODULES.map((m) => wrapModule(m, readFileSync(join(VERIFIER, m + '.mjs'), 'utf8'))).join('') + TAIL;
}

const isMain = !!process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const next = buildKitBrowserSource();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(KIT_BROWSER_PATH, 'utf8'); } catch { /* absent reads as stale */ }
    if (current !== next) {
      console.error('verifier/kit.browser.js is stale: run node scripts/build-kit-browser.mjs');
      process.exit(1);
    }
    console.log('verifier/kit.browser.js is current');
  } else {
    writeFileSync(KIT_BROWSER_PATH, next);
    console.log(`wrote verifier/kit.browser.js (${next.length} characters)`);
  }
}
