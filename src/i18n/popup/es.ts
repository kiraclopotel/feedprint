/** "a, b y c", with "e" before a word that starts with the sound i ("Facebook e Instagram"). */
const yList = (xs: string[]): string => {
  if (xs.length < 2) return xs.join('');
  const last = xs[xs.length - 1];
  return `${xs.slice(0, -1).join(', ')} ${/^h?i(?![aeou])/i.test(last) ? 'e' : 'y'} ${last}`;
};

