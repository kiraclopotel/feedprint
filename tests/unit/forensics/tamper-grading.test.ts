// ─── Key + record fixture helpers ────────────────────────────────────────────

const KEY_ALGO: EcKeyGenParams = { name: 'ECDSA', namedCurve: 'P-256' };
const SIGN_ALGO: EcdsaParams = { name: 'ECDSA', hash: { name: 'SHA-256' } };

/**
 * Generate a fresh real ECDSA P-256 keypair and install it as THIS realm's
 * current signing identity (same commit path signing.ts uses for a
 * key-restore). Calling this a second time is a genuine key rotation: the
 * previously current key stops being "current" for every subsequent
 * signHash/getPublicKeyFingerprint/verifyHash call, exactly as it would
 * after a real reinstall or key-restore on the extension.
 */
async function installFreshKey(): Promise<{ fingerprint: string; publicKey: CryptoKey }> {
  const pair = await crypto.subtle.generateKey(KEY_ALGO, true, ['sign', 'verify']);
  const privateJwk = await crypto.subtle.exportKey('jwk', pair.privateKey);
  const staged = await prepareSigningKeyRestore(privateJwk);
  const fingerprint = await commitSigningKeyRestore(staged);
  return { fingerprint, publicKey: pair.publicKey };
}

function base64UrlToBuffer(s: string): ArrayBuffer {
  const padding = '='.repeat((4 - (s.length % 4)) % 4);
  const b64 = (s + padding).replace(/-/g, '+').replace(/_/g, '/');
  const binary = atob(b64);
  const buf = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) buf[i] = binary.charCodeAt(i);
  return buf.buffer;
}

/** Synthetic record payload — fabricated content only, real record shape. */
