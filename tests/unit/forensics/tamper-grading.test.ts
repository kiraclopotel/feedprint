/** Build one record signed for real under whatever key is CURRENT right now. */
async function buildSignedRecord(i: number, prevHash: string, fingerprint: string): Promise<ForensicRecord> {
  const payload = { ...basePayload(i, prevHash), publicKeyFingerprint: fingerprint };
  const integrityHash = await computeRecordIntegrityHash(payload);
  const signature = await signHash(integrityHash);
  return { ...payload, integrityHash, signature };
}

// ─── 1. Control — the unmodified synthetic chain must verify GREEN ──────────
// If this does not pass, tamper cases A and B below prove nothing: a
// verifier that can't say "clean" clearly can't be trusted to say "broken"
// meaningfully either.

describe('tamper-grading — control (synthetic chain, real ECDSA key)', () => {
  it('an untouched, fully synthetic, singly-keyed chain verifies GREEN end to end', async () => {
    const { fingerprint } = await installFreshKey();
    const records: ForensicRecord[] = [];
    let prevHash = CHAIN_GENESIS_HASH;
    for (let i = 0; i < 5; i++) {
      const r = await buildSignedRecord(i, prevHash, fingerprint);
      records.push(r);
      prevHash = r.integrityHash;
    }

    const result = await verifyChainIntegrity(records);

    expect(result.valid).toBe(true);
    expect(result.chainLength).toBe(5);
    expect(result.brokenAt).toBeUndefined();
    expect(result.brokenKind).toBeUndefined();
    for (const r of records) {
      expect(result.perRecord?.get(r.id)).toBe('verified');
    }
    expect(integrityVerificationState(result)).toBe('verified');
    expect(summarizeForensicIntegrity(result).verificationState).toBe('verified');
  });
});

// ─── 2. Tamper case A (P-2026-07-10a) ────────────────────────────────────────
// "A two-record export with changed text, recomputed hashes/links, and
// unchanged matching-key signatures ... cannot render green."
//
// The attacker edits a record's content AFTER it was signed, then recomputes
// the record's own stored hash and the following record's chain link so both
// LOOK internally consistent. What the attacker cannot do without the
// private key is produce a new valid signature over the new hash — so both
// signatures stay exactly what they were: valid for the OLD hash, stale for
// the NEW one.

describe('tamper-grading — case A: content edited, hash/link recomputed, signature stale', () => {
  it('never reaches green, and the SPECIFIC tampered record is identified (not just "export unhappy")', async () => {
    const { fingerprint } = await installFreshKey();

    let prevHash = CHAIN_GENESIS_HASH;
    const r0 = await buildSignedRecord(0, prevHash, fingerprint);
    prevHash = r0.integrityHash;
    const r1 = await buildSignedRecord(1, prevHash, fingerprint);

    // Sanity: before tampering, r0's real signature genuinely verifies.
    expect(await verifyHash(r0.integrityHash, r0.signature!)).toBe(true);

    // Attacker edits r0's content, recomputes r0's stored hash to match the
    // new content, and patches r1's prevRecordHash + stored hash so the
    // chain link and r1's own hash both "recompute clean" too. r0.signature
    // and r1.signature are left UNCHANGED — the attacker has no private key.
    const tamperedR0Payload = { ...r0, originalText: 'TAMPERED SYNTHETIC TEXT' };
    const newHash0 = await computeRecordIntegrityHash(tamperedR0Payload);
    const tamperedR0: ForensicRecord = { ...tamperedR0Payload, integrityHash: newHash0 }; // signature: unchanged (stale)

    const patchedR1Payload = { ...r1, prevRecordHash: newHash0 };
    const newHash1 = await computeRecordIntegrityHash(patchedR1Payload);
    const patchedR1: ForensicRecord = { ...patchedR1Payload, integrityHash: newHash1 }; // signature: unchanged (stale)

    // Confirm the tamper is genuine under real crypto: the OLD signature does
    // NOT verify against the NEW hash. This is not asserted by the code under
    // test below — it is an independent check that the fixture actually
    // represents "invalid signature," not merely "different bytes."
    expect(await verifyHash(tamperedR0.integrityHash, tamperedR0.signature!)).toBe(false);

    const records = [tamperedR0, patchedR1];
    const result = await verifyChainIntegrity(records);

    expect(result.valid).toBe(false);
    expect(result.brokenKind).toBe('key-mismatch'); // hash/link recompute cleanly; only the signature fails
    expect(result.brokenAt).toBe(0);
    expect(result.perRecord?.get(tamperedR0.id)).toBe('broken'); // the SPECIFIC record, not just "the export"
    expect(result.perRecord?.get(patchedR1.id)).toBeUndefined(); // walker bails at r0; r1 is never even reached

    expect(integrityVerificationState(result)).toBe('failed');
    expect(summarizeForensicIntegrity(result).verificationState).toBe('failed'); // never green
  });
});

// ─── 3. Tamper case B (P-2026-07-10b) ────────────────────────────────────────
// "A fresh current-key export stays green; legitimate earlier-key ... records
// remain readable but render amber and never claim their signatures
// matched."
//
// A real key rotation: two records signed for real under KeyA, then the
// signing identity is rotated to KeyB (a second freshly generated real
// keypair, installed the same way a restore/reinstall would install it), and
// two more records are signed for real under KeyB. The KeyA records are
// NOT tampered — their signatures are exactly what KeyA produced. Walking
// the chain under "current key = KeyB" must render the KeyA records amber
// (prior-key / partial), never green, and never call them broken/tampered.

describe('tamper-grading — case B: real key rotation, earlier-key records still validly signed', () => {
  it('renders AMBER (partial) for earlier-key records, GREEN status for current-key records, and the whole chain stays non-failing', async () => {
    // --- KeyA era ---
    const { fingerprint: fpA, publicKey: pubA } = await installFreshKey();
    let prevHash = CHAIN_GENESIS_HASH;
    const recordsA: ForensicRecord[] = [];
    for (let i = 0; i < 2; i++) {
      const r = await buildSignedRecord(i, prevHash, fpA);
      recordsA.push(r);
      prevHash = r.integrityHash;
    }

    // Independently confirm each KeyA record is genuinely, validly signed
    // under KeyA's OWN public key, before KeyA becomes unreachable below.
    for (const r of recordsA) {
      const ok = await crypto.subtle.verify(
        SIGN_ALGO, pubA, base64UrlToBuffer(r.signature!), new TextEncoder().encode(r.integrityHash),
      );
      expect(ok).toBe(true);
    }

    // --- Rotate: KeyB becomes the current install key from here on ---
    const { fingerprint: fpB } = await installFreshKey();
    expect(fpB).not.toBe(fpA);

    const recordsB: ForensicRecord[] = [];
    for (let i = 2; i < 4; i++) {
      const r = await buildSignedRecord(i, prevHash, fpB);
      recordsB.push(r);
      prevHash = r.integrityHash;
    }

    // Genuinely (real crypto, not assumed): KeyA's signature does NOT verify
    // under the now-current KeyB public key. This is what makes the amber
    // branch below an authentic crypto mismatch rather than a label.
    expect(await verifyHash(recordsA[0].integrityHash, recordsA[0].signature!)).toBe(false);

    const records = [...recordsA, ...recordsB];
    const result = await verifyChainIntegrity(records);

    expect(result.valid).toBe(true); // non-failing: a legitimate rotation, not tampering
    expect(result.brokenKind).toBeUndefined();
    expect(result.priorKeyCount).toBe(2);
    for (const r of recordsA) expect(result.perRecord?.get(r.id)).toBe('prior-key');
    for (const r of recordsB) expect(result.perRecord?.get(r.id)).toBe('verified');

    expect(integrityVerificationState(result)).toBe('partial'); // amber
    const summary = summarizeForensicIntegrity(result);
    expect(summary.verificationState).toBe('partial'); // never claims green
    expect(summary.counts['prior-key']).toBe(2);
    expect(summary.counts.verified).toBe(2);
  });
});
